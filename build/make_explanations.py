    if not L:
        continue
    q, a = r['question'], r['answers'][r['correct']].rstrip('.')
    if q.startswith('Welches Wappen'):
        t = 'Герб земли: %s. Это Bild %d.' % (WAPPEN[L], r['correct'] + 1)
